#!/usr/bin/env node
/**
 * Deterministic classic-script bundler for cms-actor.
 *
 * LoomRealm Web Presentation Config v1 loads business scripts as ordered
 * CLASSIC <script src> elements; it never evaluates ES modules. This script
 * bundles the authored ESM sources into one self-contained IIFE that
 * registers the `cms-actor` Custom Element without any module loader.
 *
 * The transformation is intentionally dependency-free and deterministic so
 * the checked-in artifact (browser/cms-actor.browser.js) can be verified
 * byte-for-byte against the sources by `node --test` (see
 * test/browser-artifact.test.mjs).
 *
 * Usage: node scripts/build.mjs [--check]
 *   --check  exit 1 when the checked-in artifact differs from a fresh build
 */
import { spawnSync } from "node:child_process";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const componentRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const sources = {
  model: path.join(componentRoot, "src", "avatar-model.mjs"),
  element: path.join(componentRoot, "src", "cms-actor.mjs"),
};
const outputPath = path.join(componentRoot, "browser", "cms-actor.browser.js");
const HEADER = `/*! cms-actor browser entry (classic script; no module loader).
 * Generated by components/cms-actor/scripts/build.mjs — edit src/ instead.
 * Registered by LoomRealm Web Presentation Config v1 as an ordered classic
 * <script src>; MIME essence must be text/javascript. */`;

function stripExports(source) {
  // Normalize line endings so the artifact is byte-stable regardless of the
  // platform's git autocrlf behavior.
  return source
    .replace(/\r\n/g, "\n")
    .replace(/^import\s*\{[\s\S]*?\}\s*from\s*["'][^"']+["'];\s*$/gm, "")
    .replace(/^export\s+(?=(const|function|class)\b)/gm, "");
}

function bundle() {
  const model = stripExports(readFileSync(sources.model, "utf8"));
  const element = stripExports(readFileSync(sources.element, "utf8"));
  const body = `${model}\n${element}`
    .replace(/\n{3,}/g, "\n\n")
    .trim();
  const script = `${HEADER}\n(function () {\n"use strict";\n${body}\n})();\n`;
  if (/(^|\n)\s*(import|export)\s*[{"'\s]/.test(script)) {
    throw new Error("bundle still contains import/export syntax");
  }
  return script;
}

function checkSyntax(file) {
  const result = spawnSync(process.execPath, ["--check", file], { encoding: "utf8" });
  if (result.status !== 0) throw new Error(`generated bundle failed node --check:\n${result.stderr}`);
}

const check = process.argv.includes("--check");
const generated = bundle();
if (check) {
  let current = null;
  try {
    // Compare modulo CR so CRLF re-checkouts do not fail the byte check.
    current = readFileSync(outputPath, "utf8").replace(/\r\n/g, "\n");
  } catch {
    current = null;
  }
  if (current !== generated) {
    console.error("browser/cms-actor.browser.js is out of date; run: node scripts/build.mjs");
    process.exit(1);
  }
  console.log("browser/cms-actor.browser.js matches sources");
} else {
  mkdirSync(path.dirname(outputPath), { recursive: true });
  writeFileSync(outputPath, generated);
  console.log(`wrote ${path.relative(componentRoot, outputPath)} (${Buffer.byteLength(generated)} bytes)`);
}
checkSyntax(outputPath);
